#!/usr/bin/env python3
"""
Teacher-Student Dataset for training student models using pre-computed teacher outputs.
This dataset reads the outputs generated by the teacher model and provides them
for training the student model.
"""

import os
import json
import logging
from typing import Dict, List, Optional, Tuple, Union

import torch
import numpy as np
from torch.utils.data import Dataset

logger = logging.getLogger(__name__)


class TeacherStudentDataset(Dataset):
    """
    Dataset for teacher-student training that reads pre-computed teacher outputs.
    
    This dataset loads the outputs generated by the teacher model:
    - latents: Encoded image latents
    - t: Timesteps
    - text_embeddings: Text encoder outputs
    - eps_teacher: Teacher model predictions
    """
    
    def __init__(
        self,
        teacher_outputs_dir: str,
        resolution: Tuple[int, int] = (512, 512),
        network_multiplier: float = 1.0,
        debug_dataset: bool = False
    ):
        """
        Initialize the teacher-student dataset.
        
        Args:
            teacher_outputs_dir: Directory containing teacher outputs
            resolution: Target resolution for training
            network_multiplier: Network multiplier for training
            debug_dataset: Enable debug mode
        """
        super().__init__()
        
        self.teacher_outputs_dir = teacher_outputs_dir
        self.resolution = resolution
        self.network_multiplier = network_multiplier
        self.debug_dataset = debug_dataset
        
        # Load metadata
        self.metadata = self._load_metadata()
        
        # Setup image data
        self.image_data = self._setup_image_data()
        
        logger.info(f"Teacher-Student dataset initialized with {len(self.image_data)} images")
    
    def _load_metadata(self) -> Dict:
        """Load metadata from the teacher outputs directory."""
        metadata_path = os.path.join(self.teacher_outputs_dir, "metadata.json")
        
        if not os.path.exists(metadata_path):
            raise FileNotFoundError(f"Metadata file not found: {metadata_path}")
        
        with open(metadata_path, 'r') as f:
            metadata = json.load(f)
        
        logger.info(f"Loaded metadata: {metadata['total_images']} images, resolution: {metadata['resolution']}")
        return metadata
    
    def _setup_image_data(self) -> Dict[str, Dict]:
        """Setup image data structure from metadata."""
        image_data = {}
        
        for img_info in self.metadata['images']:
            image_key = f"teacher_{img_info['index']:06d}"
            
            # Create paths to teacher output files
            base_path = os.path.join(self.teacher_outputs_dir, img_info['latents_file'].replace('_latents.npy', ''))
            
            image_data[image_key] = {
                'index': img_info['index'],
                'caption': img_info['caption'],
                'original_path': img_info['original_path'],
                'latents_file': f"{base_path}_latents.npy",
                't_file': f"{base_path}_t.npy",
                'text_embeddings_file': f"{base_path}_text_embeddings.npy",
                'eps_teacher_file': f"{base_path}_eps_teacher.npy",
                'resolution': self.metadata['resolution']
            }
        
        return image_data
    
    def __len__(self) -> int:
        """Return the number of images in the dataset."""
        return len(self.image_data)
    
    def __getitem__(self, index: int) -> Dict:
        """
        Get a single training example.
        
        Returns:
            Dictionary containing:
            - latents: Image latents [1, 4, H, W]
            - t: Timestep [1]
            - text_embeddings: Text encoder outputs [1, 77, 768]
            - eps_teacher: Teacher predictions [1, 4, H, W]
            - caption: Text caption
            - network_multipliers: Network multiplier [1]
        """
        # Get image key
        image_keys = list(self.image_data.keys())
        image_key = image_keys[index]
        img_data = self.image_data[image_key]
        
        try:
            # Load teacher outputs
            latents = np.load(img_data['latents_file'])
            t = np.load(img_data['t_file'])
            text_embeddings = np.load(img_data['text_embeddings_file'])
            eps_teacher = np.load(img_data['eps_teacher_file'])
            
            # Convert to tensors
            latents = torch.from_numpy(latents).float()
            t = torch.from_numpy(t).long()
            text_embeddings = torch.from_numpy(text_embeddings).float()
            eps_teacher = torch.from_numpy(eps_teacher).float()
            
            # Create example
            example = {
                'latents': latents,
                't': t,
                'text_embeddings': text_embeddings,
                'eps_teacher': eps_teacher,
                'caption': img_data['caption'],
                'network_multipliers': torch.FloatTensor([self.network_multiplier])
            }
            
            # Add debug info if enabled
            if self.debug_dataset:
                example['image_key'] = image_key
                example['original_path'] = img_data['original_path']
                example['resolution'] = img_data['resolution']
            
            return example
            
        except Exception as e:
            logger.error(f"Error loading teacher outputs for {image_key}: {e}")
            # Return a dummy example to avoid breaking training
            dummy_latents = torch.randn(1, 4, self.resolution[1] // 8, self.resolution[0] // 8)
            dummy_t = torch.randint(0, 1000, (1,))
            dummy_text_embeddings = torch.randn(1, 77, 768)
            dummy_eps_teacher = torch.randn(1, 4, self.resolution[1] // 8, self.resolution[0] // 8)
            
            return {
                'latents': dummy_latents,
                't': dummy_t,
                'text_embeddings': dummy_text_embeddings,
                'eps_teacher': dummy_eps_teacher,
                'caption': img_data['caption'],
                'network_multipliers': torch.FloatTensor([self.network_multiplier])
            }
    
    def get_image_info(self, index: int) -> Optional[Dict]:
        """Get image information without loading the actual data."""
        if index >= len(self):
            return None
        
        image_keys = list(self.image_data.keys())
        image_key = image_keys[index]
        return self.image_data[image_key]
    
    def get_caption(self, index: int) -> Optional[str]:
        """Get caption for a specific image index."""
        img_info = self.get_image_info(index)
        return img_info['caption'] if img_info else None
    
    def get_resolution(self) -> Tuple[int, int]:
        """Get the resolution used for this dataset."""
        return self.resolution
    
    def get_network_multiplier(self) -> float:
        """Get the network multiplier for this dataset."""
        return self.network_multiplier


class TeacherStudentDataLoader:
    """
    DataLoader wrapper for teacher-student training.
    This provides convenient access to teacher outputs for training.
    """
    
    def __init__(
        self,
        teacher_outputs_dir: str,
        batch_size: int = 1,
        resolution: Tuple[int, int] = (512, 512),
        network_multiplier: float = 1.0,
        debug_dataset: bool = False,
        shuffle: bool = True
    ):
        """
        Initialize the data loader.
        
        Args:
            teacher_outputs_dir: Directory containing teacher outputs
            batch_size: Batch size for training
            resolution: Target resolution
            network_multiplier: Network multiplier
            debug_dataset: Enable debug mode
            shuffle: Whether to shuffle the dataset
        """
        self.dataset = TeacherStudentDataset(
            teacher_outputs_dir=teacher_outputs_dir,
            resolution=resolution,
            network_multiplier=network_multiplier,
            debug_dataset=debug_dataset
        )
        
        self.batch_size = batch_size
        self.shuffle = shuffle
        
        # Create indices for batching
        self.indices = list(range(len(self.dataset)))
        if self.shuffle:
            np.random.shuffle(self.indices)
        
        self.current_index = 0
    
    def __len__(self) -> int:
        """Return the number of batches."""
        return (len(self.dataset) + self.batch_size - 1) // self.batch_size
    
    def __iter__(self):
        """Reset iterator."""
        self.current_index = 0
        if self.shuffle:
            np.random.shuffle(self.indices)
        return self
    
    def __next__(self) -> Dict:
        """Get next batch."""
        if self.current_index >= len(self.dataset):
            raise StopIteration
        
        # Collect batch items
        batch_items = []
        for _ in range(self.batch_size):
            if self.current_index >= len(self.dataset):
                break
            
            item = self.dataset[self.indices[self.current_index]]
            batch_items.append(item)
            self.current_index += 1
        
        # Stack batch items
        batch = self._stack_batch(batch_items)
        return batch
    
    def _stack_batch(self, items: List[Dict]) -> Dict:
        """Stack multiple items into a batch."""
        if not items:
            return {}
        
        batch = {}
        
        # Stack tensors
        for key in ['latents', 't', 'text_embeddings', 'eps_teacher', 'network_multipliers']:
            if key in items[0]:
                batch[key] = torch.stack([item[key] for item in items])
        
        # Collect non-tensor data
        if 'caption' in items[0]:
            batch['captions'] = [item['caption'] for item in items]
        
        # Add debug info if available
        if 'image_key' in items[0]:
            batch['image_keys'] = [item['image_key'] for item in items]
        
        return batch
    
    def get_dataset_info(self) -> Dict:
        """Get information about the dataset."""
        return {
            'total_images': len(self.dataset),
            'batch_size': self.batch_size,
            'resolution': self.dataset.get_resolution(),
            'network_multiplier': self.dataset.get_network_multiplier(),
            'teacher_outputs_dir': self.dataset.teacher_outputs_dir
        }